export type CardName = keyof typeof CARDS

/**
 * The card for one industry page.
 *
 * ⚠️ THROWS rather than falling back. generateMetadata runs during the
 * prerender, so an industry added to industries.ts without a matching card in
 * make-page-cards.py fails the BUILD, loudly, with the fix in the message. A
 * fallback here would ship a page wearing another page's card and nothing would
 * say so — which is the failure this whole file exists to prevent.
 */
export function industryCard(slug: string): CardName {
  const key = `ind-${slug}`
  if (!(key in CARDS)) {
    throw new Error(
      `No social card for industry "${slug}". Add 'ind-${slug}' to CARDS in ` +
      `marketing/scripts/make-page-cards.py, regenerate, and copy the PNG into public/images.`,
    )
  }
  return key as CardName
}


/**
 * Returns the `openGraph` and `twitter` halves of a page's metadata, spread
 * into it. Every page on this site sets its social card through here.
 */
export function social(name: CardName, og: OpenGraph): Pick<Metadata, 'openGraph' | 'twitter'> {
  const [url, alt] = CARDS[name]
  return {
    openGraph: {
      siteName: 'JAK Labs',
      ...og,
      images: [{ url, width: 1200, height: 630, alt }],
    },
    twitter: {
      card: 'summary_large_image',
      title: og.title ?? undefined,
      description: og.description ?? undefined,
      images: [url],
    },
  }
}
